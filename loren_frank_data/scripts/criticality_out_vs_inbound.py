def spike_train_for_epoch(tetrode_keys: list, neuron_info: pd.DataFrame, animals: dict):
    # neuron counter to assess validity of data
    neuron_counter = 0
    
    # spikes list to collect all spiking times for areaepoch combination
    all_spikes_list = []

    # iterate over all tetrodes belonging to the epoch
    for tetrode_key in tetrode_keys:
        try:
 
            # get all neurons belonging to one tetrode
            neuron_numbers = neuron_info.loc[tetrode_key].index.to_list()
            
            # extract the spiking times for all neurons and append them to a list
            for neuron in neuron_numbers:
                neuron_key = tetrode_key + (neuron,)
                spikes = lfdp.neurons.get_spikes_dataframe(neuron_key, animals)
                all_spikes_list.append(spikes)
            
            # update neuron counter
            neuron_counter += len(neuron_numbers)
        
        # continue if there are no neurons for the tetrode
        except Exception as e:
            print(e)
            print('no neurons for tetrode:', tetrode_key)
            continue

    # Integrate all spikes into single series
    all_spikes = series_list_to_series(all_spikes_list)
    
    return all_spikes, neuron_counter
    
    
def series_list_to_series(series_list):
    """
    Concatenates a list of series into a single series, summing up double occurences and sorting the series
    """
    all_spikes = pd.concat(series_list)
    all_spikes = all_spikes.groupby(all_spikes.index).sum()
    all_spikes = all_spikes.sort_index()
    return all_spikes


def find_arm_transitions(df, threshold = 5):
    """_summary_

    Args:
        df (pd.Dataframe): position dataframe as generated by lfdp.get_position_dataframe
        threshold (int, optional): Minimal time interval to be considered, in s. Defaults to 5.

    Returns:
        dict: contains for each arm a list of tuples with the start and end time of each visit
    """
    # Get where the arm name changes
    df['previous_arm'] = df['arm_name'].shift()
    df['transition'] = df['arm_name'] != df['previous_arm']

    # Find transition points
    transition_times = df.index[df['transition']].tolist()

    # Create a dictionary to store intervals
    intervals = {'Left Arm': [], 'Center Arm': [], 'Right Arm': []}

    # starting point and time of first interval
    previous_arm = df.iloc[0]['arm_name']
    interval_start = df.index[0]
    
    # for each transition, add the interval to the dictionary
    # transition times are the mean of pre and post timestamp
    for i, timestamp in enumerate(df.index):
        if df.loc[timestamp, 'transition']:
            interval_end = (timestamp + df.index[i+1]) / 2
            intervals[previous_arm].append((interval_start, interval_end))
            interval_start = interval_end
            previous_arm = df.loc[timestamp, 'arm_name']
        
    # Add the last interval (from last transition to the final timestamp)
    intervals[previous_arm].append((interval_start, df.index[-1]))

    # Remove intervals smaller than threshold
    if threshold is not None:
        for arm in intervals.keys():
            intervals[arm] = [interval for interval in intervals[arm] if interval[1] - interval[0] > pd.Timedelta(seconds=threshold)]

    return intervals
        

